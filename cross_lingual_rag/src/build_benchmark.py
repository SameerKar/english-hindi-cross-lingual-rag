def generate_benchmark_files(output_dir: Path):
    """Writes questions.csv and gold_labels.jsonl."""
    output_dir.mkdir(parents=True, exist_ok=True)

    csv_path = output_dir / "questions.csv"
    jsonl_path = output_dir / "gold_labels.jsonl"

    fieldnames = [
        "question_id", "subject", "category", "question_en", "question_hi",
        "gold_answer", "answerable", "gold_document_id", "gold_page", "gold_chunk_id", "notes"
    ]

    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, quoting=csv.QUOTE_ALL)
        writer.writeheader()
        for item in BENCHMARK_DATA:
            writer.writerow(item)

    with open(jsonl_path, "w", encoding="utf-8") as f:
        for item in BENCHMARK_DATA:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")

    print(f"[Benchmark Generator] Successfully generated {len(BENCHMARK_DATA)} questions.")
    print(f"CSV saved to: {csv_path}")
    print(f"JSONL saved to: {jsonl_path}")


if __name__ == "__main__":
    out_dir = Path(__file__).resolve().parent.parent / "data" / "benchmark"
    generate_benchmark_files(out_dir)

